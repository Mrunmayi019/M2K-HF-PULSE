"""HANDOFF.md P2: "Benchmark against an established clinical risk score."

Computes the MAGGIC score (src/analytics/benchmark_scores.py) for every patient in the Phase 4
batch simulation dataset (data/simulation_runs/features_dataset.csv, 117 successful Pulse runs)
and compares it against this project's own primary risk score (src/analytics/risk_score.py).

No Docker/Pulse required -- both the hemodynamic features and the clinical fields already exist
on disk from prior sessions.

IMPORTANT: this is agreement between two *model outputs*, not a benchmark against real outcomes
-- neither score has been validated against real mortality/hospitalization data for this cohort
(see HANDOFF.md P1's "real clinical outcome validation" item, still not started). Read the
"agreement" numbers below as "how much do these two independently-derived scoring approaches
agree," not as evidence either one is correct.

Run from repo root: python -m scripts.benchmark_comparison
Writes: data/benchmark_comparison/maggic_vs_risk_score.csv, docs/benchmark_comparison.md
"""
import pathlib

import pandas as pd
from scipy import stats

from src.analytics.benchmark_scores import compute_maggic_score
from src.analytics.risk_score import compute_risk_score

FEATURES_PATH = pathlib.Path("data/simulation_runs/features_dataset.csv")
PATIENTS_PATH = pathlib.Path("data/synthetic/patients.csv")
OUT_CSV = pathlib.Path("data/benchmark_comparison/maggic_vs_risk_score.csv")
OUT_DOC = pathlib.Path("docs/benchmark_comparison.md")


def build_comparison_table() -> pd.DataFrame:
    features = pd.read_csv(FEATURES_PATH)
    patients = pd.read_csv(PATIENTS_PATH)[["patient_id", "age", "sex", "bmi", "nyha_class"]]
    df = features.merge(patients, on="patient_id", how="inner", validate="one_to_one")
    if len(df) != len(features):
        missing = set(features["patient_id"]) - set(df["patient_id"])
        raise RuntimeError(f"{len(missing)} patient_id(s) in features_dataset.csv not found in patients.csv: {sorted(missing)[:5]}...")

    risk_rows = df.apply(
        lambda r: compute_risk_score(
            hr_rise=r["hr_rise"], map_drop=r["map_drop"], co_drop_pct=r["co_drop_pct"],
            compensation_flag=r["compensation_flag"], instability_flag=r["instability_flag"],
            map_start=r["map_start"],
        ),
        axis=1,
    )
    df["risk_score"] = risk_rows.apply(lambda r: r["risk_score"])
    df["risk_bucket"] = risk_rows.apply(lambda r: r["risk_bucket"])

    maggic_rows = df.apply(
        lambda r: compute_maggic_score(
            age=r["age"], sex=r["sex"], ejection_fraction_pct=r["ejection_fraction_pct"],
            nyha_class=r["nyha_class"], bmi=r["bmi"],
        ),
        axis=1,
    )
    df["maggic_score"] = maggic_rows.apply(lambda r: r["maggic_score"])

    # Tertile split of THIS cohort's own maggic_score distribution -- an engineering choice for
    # comparison purposes, not a clinically-cited MAGGIC cutoff (none was found/verified -- see
    # benchmark_scores.py's module docstring). Mirrors risk_score.py's own tertile-split framing
    # for LOW_HIGH_BOUNDARY/MODERATE_HIGH_BOUNDARY.
    df["maggic_bucket"] = pd.qcut(df["maggic_score"], q=3, labels=["LOW", "MODERATE", "HIGH"])

    return df


def summarize(df: pd.DataFrame) -> str:
    spearman = stats.spearmanr(df["risk_score"], df["maggic_score"])
    agree_mask = df["risk_bucket"] == df["maggic_bucket"].astype(str)
    pct_agree = 100 * agree_mask.mean()

    crosstab = pd.crosstab(df["risk_bucket"], df["maggic_bucket"], margins=True)

    by_scenario = (
        df.groupby("scenario_type")
        .apply(lambda g: pd.Series({
            "n": len(g),
            "spearman_r": stats.spearmanr(g["risk_score"], g["maggic_score"]).statistic if len(g) > 2 else float("nan"),
            "pct_bucket_agree": 100 * (g["risk_bucket"] == g["maggic_bucket"].astype(str)).mean(),
        }))
    )

    lines = [
        "# Benchmark comparison: risk_score.py vs. MAGGIC",
        "",
        f"Generated by `scripts/benchmark_comparison.py` against "
        f"`data/simulation_runs/features_dataset.csv` (n={len(df)} successful Phase 4 batch runs, "
        "joined with `data/synthetic/patients.csv` for age/sex/BMI/NYHA).",
        "",
        "**Read this as agreement between two model outputs, not validation against real "
        "outcomes** -- see this script's own module docstring and "
        "`src/analytics/benchmark_scores.py`'s module docstring for exactly which MAGGIC inputs "
        "are real per-patient data vs. fixed assumed defaults (age/sex/EF/NYHA/BMI are real; "
        "systolic BP, creatinine, diabetes/COPD/smoking, HF duration, and beta-blocker/ACEI-ARB "
        "use are fixed constants, not measured).",
        "",
        "## Overall agreement",
        "",
        f"- Spearman correlation (risk_score vs. maggic_score): r={spearman.statistic:.3f}, "
        f"p={spearman.pvalue:.4f}",
        f"- Risk-tier agreement (risk_bucket vs. maggic_bucket, maggic tertile-split on this "
        f"cohort): {pct_agree:.1f}% (a random pairing of two independent 3-category splits would "
        "land around 33% by chance alone -- read the margin above that, not the raw number, as "
        "the signal)",
        "",
        "## Confusion matrix (risk_bucket rows x maggic_bucket columns)",
        "",
        "```",
        crosstab.to_string(),
        "```",
        "",
        "## By scenario type",
        "",
        "```",
        by_scenario.round(3).to_string(),
        "```",
        "",
        "## Interpretation",
        "",
        "A low/negative correlation would not necessarily mean either score is wrong -- "
        "risk_score.py measures acute hemodynamic response to one simulated Pulse encounter plus "
        "chronic baseline congestion (the fluid_overload fix), while MAGGIC is a static "
        "population-mortality score from clinical intake variables. They are measuring related "
        "but distinct things by design. What this comparison actually establishes: whether this "
        "project's risk output is at least directionally consistent with an externally validated "
        "score on the same patients, which is the minimum bar HANDOFF.md's P2 item asks for -- "
        "not equivalence, and not a substitute for the real clinical outcome validation in P1.",
    ]
    return "\n".join(lines)


def main():
    df = build_comparison_table()
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUT_CSV, index=False)
    print(f"Wrote {OUT_CSV} ({len(df)} rows)")

    doc = summarize(df)
    OUT_DOC.write_text(doc)
    print(f"Wrote {OUT_DOC}")
    print()
    print(doc)


if __name__ == "__main__":
    main()
